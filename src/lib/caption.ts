const CTAS: string[] = [
  "اگه خوشت اومد، یه قلب ❤️ برامون بذار!",
  "با دوستات هم به اشتراک بذار 🌟",
  "برای دیدن ویدیوهای بیشتر، ما رو دنبال کن 🎈",
  "نظرت رو برامون کامنت کن 💬",
];

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Build a ready-to-paste TikTok caption: hook + title + CTA + hashtags.
 */
export function buildCaption(
  cat: Category,
  title: string,
  hashtags: string
): string {
  const hook = pick(HOOKS[cat.key] ?? HOOKS["حیوانات"]);
  const cta = pick(CTAS);
  const tags = hashtags.trim() ? `\n\n${hashtags.trim()}` : "";
  return `${hook}\n\n🎬 ${title}\n\n${cta}${tags}\n\n#کودک #آموزش_کودکان #تیک_تاک_کودک`;
}
